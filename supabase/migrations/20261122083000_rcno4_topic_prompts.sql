-- お題の登録前に作られた開催中のボード（既定の文言のまま）に、今週のお題を入れる。
-- 手動で変えたお題（topic_source = 'custom'）はそのまま残す。
update public.boards b
   set topic = w.topic, prompt_id = w.prompt_id
  from public.boards b2
  cross join lateral private.ruuuto_weekly_prompt(b2.opens_at) w
 where b.id = b2.id
   and b.status = 'open'
   and b.topic_source = 'weekly'
   and b.prompt_id is null
   and w.prompt_id is not null;
